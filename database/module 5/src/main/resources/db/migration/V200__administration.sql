CREATE TABLE administration_events (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,actor_id BIGINT NOT NULL,action VARCHAR(40) NOT NULL,
 subject_id BIGINT NOT NULL,note VARCHAR(1000) NOT NULL,created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_admin_actor FOREIGN KEY(actor_id) REFERENCES users(id),
 CONSTRAINT fk_admin_subject FOREIGN KEY(subject_id) REFERENCES users(id)
);
